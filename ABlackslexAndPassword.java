import java.util.*;

public class ABlackslexAndPassword {
    public static void main(String[] args) {

        Scanner sc = new Scanner(System.in);

        int n = sc.nextInt();

        while (n-- > 0) {

            long k = sc.nextLong();
            long x = sc.nextLong();

            System.out.println(k * x + 1);
        }
    }
} 
    

